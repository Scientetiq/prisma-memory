const dayWords = (day: string): string => {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(day);
  if (!m) return day;
  const month = Number(m[2]);
  return month >= 1 && month <= 12 ? dates.dayMonth(Number(m[3]), month) : `${Number(m[3])} ${m[2]}`;
};
