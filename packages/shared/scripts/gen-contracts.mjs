#!/usr/bin/env node
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("../../../", import.meta.url));
const ENUMS = `${ROOT}contracts/schema/enums.json`;
const POLICY = `${ROOT}contracts/edge/settings-policy.json`;
const EDGE_META = `${ROOT}contracts/edge/edge-meta.schema.json`;
const GEN_TS = `${ROOT}packages/shared/src/enums.gen.ts`;

export const EDGE_META_DERIVED = ["fts_configs", "login_paused_until", "mfa", "mfa_style"];

export function enumValues(reg, name) {
  const e = reg.enums[name];
  const out = [];
  for (const stage of reg.stages) for (const v of e.values?.[stage] ?? []) if (!out.includes(v)) out.push(v);
  return out;
}

export function genEnumsTs(reg) {
  const all = {};
  for (const name of Object.keys(reg.enums)) all[name] = enumValues(reg, name);
  const lit = (a) => JSON.stringify(a);
  const codes = reg.enums["login.checks.kind"]?.codes ?? {};
  return [
    "// Generated by packages/shared/scripts/gen-contracts.mjs from contracts/schema/enums.json. Do not edit by hand:",
    "// add the new value to the registry, then run pnpm contracts:gen. CI checks this file against the registry (--check).",
    "",
    "/** All enumerations of the registry, with values in registry order. */",
    `export const ENUMS = ${JSON.stringify(all, null, 2)} as const;`,
    "",
    "/** Settings categories (settings.category). */",
    `export const SETTINGS_CATEGORIES = ${lit(all["settings.category"])} as const;`,
    "export type SettingsCategory = (typeof SETTINGS_CATEGORIES)[number];",
    "",
    "/** Kinds of mail in the mail_outbox queue (the single source of MAIL_KINDS in smtp.ts). */",
    `export const MAIL_KINDS = ${lit(all["mail_outbox.kind"])} as const;`,
    "export type MailKind = (typeof MAIL_KINDS)[number];",
    "",
    "/** Event types of the audit_events.event_type journal column. */",
    `export const AUDIT_EVENT_TYPES = ${lit(all["audit_events.event_type"])} as const;`,
    "export type AuditEventType = (typeof AUDIT_EVENT_TYPES)[number];",
    "",
    "/** Second-factor level of a connection (the login-check contract). */",
    `export const MFA_LEVELS = ${lit(all["mfa_level"])} as const;`,
    "export type MfaLevel = (typeof MFA_LEVELS)[number];",
    "",
    "/** Login-check request kinds: name to number in the smallint column (the login-check contract). */",
    `export const LOGIN_CHECK_KINDS = ${JSON.stringify(codes)} as const;`,
    "export type LoginCheckKind = keyof typeof LOGIN_CHECK_KINDS;",
    "",
    "/** Run mode of a service in service_heartbeats. */",
    `export const RUN_MODES = ${lit(all["service_heartbeats.run_mode"])} as const;`,
    "export type RunMode = (typeof RUN_MODES)[number];",
    "",
  ].join("\n");
}

export function edgeMetaKeys(policy) {
  const bare = [];
  for (const [path, p] of Object.entries(policy.keys)) {
    if (p.where !== "edge" && p.where !== "both") continue;
    if (p.audit === "fingerprint") throw new Error(`settings-policy.json ${path}: key audit: fingerprint with where ${p.where} does not go to the edge`);
    bare.push(path.slice(path.indexOf(".") + 1));
  }
  return [...new Set([...bare, ...EDGE_META_DERIVED])].sort();
}

function main() {
  const check = process.argv.includes("--check");
  const reg = JSON.parse(readFileSync(ENUMS, "utf8"));
  const policy = JSON.parse(readFileSync(POLICY, "utf8"));
  const meta = JSON.parse(readFileSync(EDGE_META, "utf8"));
  meta.propertyNames = { ...(meta.propertyNames ?? {}), enum: edgeMetaKeys(policy) };
  const want = [
    [GEN_TS, genEnumsTs(reg)],
    [EDGE_META, `${JSON.stringify(meta, null, 2)}\n`],
  ];
  let bad = 0;
  for (const [file, text] of want) {
    let have = null;
    try { have = readFileSync(file, "utf8"); } catch { }
    if (have === text) continue;
    if (check) { console.error(`contracts:gen --check: ${file.slice(ROOT.length)} differs from the registry — run pnpm contracts:gen`); bad++; }
    else { writeFileSync(file, text); console.log(`written ${file.slice(ROOT.length)}`); }
  }
  if (bad) process.exit(1);
  if (check) console.log("contracts:gen --check: generated files match the contracts");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) main();
