#!/usr/bin/env node
// The list of the production npm packages that pnpm-lock.yaml pins: name, version and licence of each, in
// third_party_licenses/npm-production-packages.md. Node.js standard library only; no network.
//
//   node tools/licenses/npm-packages.mjs                      write the list
//   node tools/licenses/npm-packages.mjs --check              exit 1 when the list differs from what the lock file gives
//   node tools/licenses/npm-packages.mjs --verify-installed   exit 1 when a listed licence differs from the installed package
//   --root <dir>         the repository to read (default: two folders above this file)
//   --licences <file>    a JSON object of package key ("name", then "@", then "version") to licence, read when writing
//
// The production set: the dependencies and optionalDependencies of every importer of the lock file, followed through
// the dependencies and optionalDependencies of its snapshots; workspace links are not packages, and devDependencies are
// not followed. A package is listed once per name and version; the peer suffix of a snapshot key is not part of the version.
// When writing, the licence of a package comes from OVERRIDES (below), then from the list itself (same name and
// version), then from the --licences file, then from the installed package under node_modules/.pnpm; a package whose
// licence is not known stops the write and nothing is written. A licence is never guessed: a new package gets its
// licence from the installed package or from a --licences file made from the registry's own data.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const LIST = "third_party_licenses/npm-production-packages.md";
const HEAD = [
  "# npm production packages",
  "",
  "Generated by `node tools/licenses/npm-packages.mjs` from `pnpm-lock.yaml`; do not edit it by hand.",
  "`node tools/licenses/npm-packages.mjs --check` fails when this list and the lock file differ.",
  "",
  "The list holds the production set: the `dependencies` and `optionalDependencies` of every package of this repository",
  "and everything they depend on, at the versions the lock file pins. Development tools are not listed. The build on your",
  "server downloads these packages from the public npm registry; each package keeps its own licence and notices.",
  "",
];

// Packages whose own LICENSE file grants more than the "license" field of their package.json states. The list shows
// `licence`, the terms of the LICENSE file, and --check expects it; --verify-installed expects the installed
// package.json to state `declared`. Key: name, "@", version. Each entry was read by hand in the package's LICENSE file.
const OVERRIDES = new Map([
  ["@modelcontextprotocol/client@2.3.0", { licence: "Apache-2.0 AND MIT", declared: "Apache-2.0" }],
  ["@modelcontextprotocol/core@2.3.0", { licence: "Apache-2.0 AND MIT", declared: "Apache-2.0" }],
  ["@modelcontextprotocol/node@2.1.0", { licence: "Apache-2.0 AND MIT", declared: "MIT" }],
  ["@modelcontextprotocol/server@2.3.0", { licence: "Apache-2.0 AND MIT", declared: "Apache-2.0" }],
]);

function fail(message, code = 1) {
  console.log("npm-packages: " + message);
  process.exit(code);
}

function args(argv) {
  const out = { mode: "write", root: resolve(dirname(fileURLToPath(import.meta.url)), "..", ".."), licences: null };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--check") out.mode = "check";
    else if (a === "--verify-installed") out.mode = "verify";
    else if (a === "--root" && i + 1 < argv.length) out.root = resolve(argv[++i]);
    else if (a === "--licences" && i + 1 < argv.length) out.licences = resolve(argv[++i]);
    else fail("unknown argument " + JSON.stringify(a) + " (use --check, --verify-installed, --root <dir>, --licences <file>)", 2);
  }
  return out;
}

const unquote = (s) => (s.length > 1 && s[0] === "'" && s.endsWith("'") ? s.slice(1, -1) : s);
const plain = (v) => v.split("(")[0];
const key = (name, version) => name + "@" + version;

/** The sections of a lockfile v9 as lines: top-level key to its indented lines. */
function sections(text) {
  const out = new Map();
  let cur = null;
  for (const line of text.split("\n")) {
    if (/^\S/.test(line)) {
      cur = line.replace(/:.*$/, "");
      out.set(cur, []);
    } else if (cur !== null) out.get(cur).push(line);
  }
  return out;
}

/** The production set of the lock file: Map key -> { name, version }. */
function productionSet(lockText) {
  const s = sections(lockText);
  if (!/^lockfileVersion: '9\.0'$/m.test(lockText)) throw new Error("pnpm-lock.yaml is not lockfile version 9.0");
  if (!s.has("importers") || !s.has("snapshots")) throw new Error("pnpm-lock.yaml has no importers or snapshots section");
  const start = [];
  let kind = null;
  let name = null;
  for (const line of s.get("importers")) {
    let m;
    if ((m = /^ {4}(\w+):$/.exec(line))) kind = m[1];
    else if ((m = /^ {6}(\S.*):$/.exec(line))) name = unquote(m[1]);
    else if ((m = /^ {8}version: (\S+)$/.exec(line))) {
      if ((kind === "dependencies" || kind === "optionalDependencies") && !m[1].startsWith("link:")) start.push([name, unquote(m[1])]);
    } else if (/^ {2}\S/.test(line)) kind = null;
  }
  const snaps = new Map();
  let snap = null;
  kind = null;
  for (const line of s.get("snapshots")) {
    let m;
    if ((m = /^ {2}(\S.*?):(?: \{\})?$/.exec(line))) {
      snap = unquote(m[1]);
      snaps.set(snap, []);
      kind = null;
    } else if ((m = /^ {4}(\w+):$/.exec(line))) kind = m[1];
    else if ((m = /^ {6}(\S+): (\S+)$/.exec(line)) && snap !== null) {
      if (kind === "dependencies" || kind === "optionalDependencies") snaps.get(snap).push([unquote(m[1]), unquote(m[2])]);
    }
  }
  const out = new Map();
  const seen = new Set();
  const todo = [...start];
  while (todo.length) {
    const [n, v] = todo.pop();
    if (v.startsWith("link:")) continue;
    const full = key(n, v);
    if (seen.has(full)) continue;
    seen.add(full);
    if (!snaps.has(full)) throw new Error("pnpm-lock.yaml has no snapshot for " + full);
    out.set(key(n, plain(v)), { name: n, version: plain(v) });
    todo.push(...snaps.get(full));
  }
  return out;
}

const ROW = /^\| `([^`]+)` \| ([^ |]+) \| (.+) \|$/;

function readList(path) {
  const rows = new Map();
  if (!existsSync(path)) return rows;
  for (const line of readFileSync(path, "utf8").split("\n")) {
    const m = ROW.exec(line);
    if (m) rows.set(key(m[1], m[2]), m[3]);
  }
  return rows;
}

/** The listed licences with the licence of each OVERRIDES entry in its place. */
function withOverrides(listed) {
  const out = new Map(listed);
  for (const [k, o] of OVERRIDES) out.set(k, o.licence);
  return out;
}

function render(set, licence) {
  const rows = [...set.values()].sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : a.version < b.version ? -1 : a.version > b.version ? 1 : 0));
  const counts = new Map();
  for (const r of rows) counts.set(licence.get(key(r.name, r.version)), (counts.get(licence.get(key(r.name, r.version))) ?? 0) + 1);
  const totals = [...counts.entries()].sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : 1)).map(([l, n]) => `${l} ${n}`).join(", ");
  const lines = [...HEAD, `Packages: ${rows.length}. Licences: ${totals}.`, "", "| Package | Version | Licence |", "| --- | --- | --- |"];
  for (const r of rows) lines.push(`| \`${r.name}\` | ${r.version} | ${licence.get(key(r.name, r.version))} |`);
  return lines.join("\n") + "\n";
}

function installedLicence(root, name, version) {
  const store = join(root, "node_modules", ".pnpm");
  if (!existsSync(store)) return null;
  const prefix = key(name.replace("/", "+"), version);
  for (const dir of readdirSync(store)) {
    if (dir !== prefix && !dir.startsWith(prefix + "_")) continue;
    const manifest = join(store, dir, "node_modules", name, "package.json");
    if (!existsSync(manifest)) continue;
    const pkg = JSON.parse(readFileSync(manifest, "utf8"));
    if (pkg.version !== version) continue;
    const l = pkg.license ?? pkg.licenses;
    if (typeof l === "string") return l;
    if (l && typeof l === "object" && !Array.isArray(l) && typeof l.type === "string") return l.type;
    if (Array.isArray(l) && l.length) return l.map((x) => (typeof x === "string" ? x : x.type)).join(" OR ");
    return null;
  }
  return null;
}

const opt = args(process.argv.slice(2));
const lockPath = join(opt.root, "pnpm-lock.yaml");
const listPath = join(opt.root, LIST);
let set;
try {
  set = productionSet(readFileSync(lockPath, "utf8"));
} catch (e) {
  fail(String(e.message ?? e));
}
const listed = readList(listPath);

if (opt.mode === "check") {
  const missing = [...set.keys()].filter((k) => !listed.has(k)).sort();
  const extra = [...listed.keys()].filter((k) => !set.has(k)).sort();
  const text = existsSync(listPath) ? readFileSync(listPath, "utf8") : "";
  const same = !missing.length && !extra.length && text === render(set, withOverrides(listed));
  if (same) {
    console.log(`npm-packages: the list matches pnpm-lock.yaml (${set.size} packages)`);
    process.exit(0);
  }
  console.log(`npm-packages: ${LIST} differs from pnpm-lock.yaml`);
  for (const k of missing) console.log("  in the lock file, not in the list: " + k);
  for (const k of extra) console.log("  in the list, not in the lock file: " + k);
  if (!missing.length && !extra.length) console.log("  the text differs from the generated text (run node tools/licenses/npm-packages.mjs to rewrite it)");
  process.exit(1);
}

if (opt.mode === "verify") {
  let compared = 0;
  let absent = 0;
  const differ = [];
  for (const [k, r] of [...set.entries()].sort()) {
    const got = installedLicence(opt.root, r.name, r.version);
    if (got === null) {
      absent++;
      continue;
    }
    compared++;
    const o = OVERRIDES.get(k);
    if (o && got !== o.declared) differ.push(`  differs: ${k}: override expects package.json ${o.declared}, installed ${got}`);
    else if (!o && listed.get(k) !== got) differ.push(`  differs: ${k}: list ${listed.get(k) ?? "(not listed)"}, installed ${got}`);
  }
  console.log(`npm-packages: licences compared with the installed packages: ${compared}; differ: ${differ.length}; not installed: ${absent}`);
  for (const d of differ) console.log(d);
  process.exit(differ.length ? 1 : 0);
}

const extraLicences = opt.licences ? JSON.parse(readFileSync(opt.licences, "utf8")) : {};
const licence = new Map();
const unknown = [];
for (const [k, r] of set) {
  const l = OVERRIDES.get(k)?.licence ?? listed.get(k) ?? extraLicences[k] ?? installedLicence(opt.root, r.name, r.version);
  if (typeof l === "string" && l.length && !l.includes("|")) licence.set(k, l);
  else unknown.push(k);
}
if (unknown.length) fail("no licence known for " + unknown.sort().join(", ") + " (install the dependencies first); nothing written");
mkdirSync(dirname(listPath), { recursive: true });
writeFileSync(listPath, render(set, licence));
console.log(`npm-packages: wrote ${LIST} (${set.size} packages)`);
